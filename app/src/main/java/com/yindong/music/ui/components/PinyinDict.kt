    /**
     * 拼音匹配：返回候选汉字列表
     * 1. 先匹配词组（多音节），若命中返回词组
     * 2. 再匹配单音节
     * 3. 最后做前缀匹配
     */
    fun match(pinyin: String): List<String> {
        if (pinyin.isBlank()) return emptyList()
        val lower = pinyin.lowercase().trim()

        val result = mutableListOf<String>()

        // 1. 词组精确匹配
        phrases[lower]?.let { result.add(it) }

        // 2. 词组前缀匹配
        phrases.keys.filter { it.startsWith(lower) && it != lower }
            .take(8)
            .forEach { result.add(phrases[it]!!) }

        // 3. 单音节精确匹配
        syllables[lower]?.forEach { ch ->
            val charStr = ch.toString()
            if (charStr !in result) result.add(charStr)
        }

        // 4. 单音节前缀匹配
        syllables.keys.filter { it.startsWith(lower) && it != lower }
            .take(5)
            .forEach { key ->
                syllables[key]!!.forEach { ch ->
                    val charStr = ch.toString()
                    if (charStr !in result) result.add(charStr)
                }
            }

        return result.take(20)
    }
